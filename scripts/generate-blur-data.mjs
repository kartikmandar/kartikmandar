// Writes tiny blurred placeholders for the images in public/media to
// src/data/blurData.generated.ts. Re-run after adding images: node scripts/generate-blur-data.mjs
import fs from 'node:fs'
import path from 'node:path'
import sharp from 'sharp'

const mediaDir = new URL('../public/media/', import.meta.url).pathname
const outFile = new URL('../src/data/blurData.generated.ts', import.meta.url).pathname
const sizedVariant = /-\d+x\d+\.[a-z]+$/i

const entries = []
for (const file of fs.readdirSync(mediaDir).sort()) {
  if (!/\.(png|jpe?g)$/i.test(file) || sizedVariant.test(file)) continue
  const buffer = await sharp(path.join(mediaDir, file)).rotate().resize(16).webp({ quality: 40 }).toBuffer()
  entries.push(`  ${JSON.stringify(`/media/${file}`)}: 'data:image/webp;base64,${buffer.toString('base64')}',`)
}

fs.writeFileSync(outFile, `// Generated by scripts/generate-blur-data.mjs. Do not edit by hand.
export const BLUR_DATA: Record<string, string> = {
${entries.join('\n')}
}
`)
console.log(`${entries.length} placeholders`)
